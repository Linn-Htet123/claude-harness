#!/usr/bin/env bash
G="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/guardrails.sh"
PASS=0; FAIL=0
t() { # label, expected(deny|allow), json
  r=$(printf '%s' "$3" | "$G")
  if [ -n "$r" ]; then got=deny; why="$(echo "$r" | jq -r .hookSpecificOutput.permissionDecisionReason | cut -c1-58)"; else got=allow; why=""; fi
  if [ "$got" = "$2" ]; then PASS=$((PASS+1)); mark="ok  "; else FAIL=$((FAIL+1)); mark="BAD "; fi
  printf '%s %-46s -> %-5s %s\n' "$mark" "$1" "$got" "$why"
}
b() { printf '{"tool_name":"Bash","tool_input":{"command":"%s"}}' "$1"; }
r() { printf '{"tool_name":"Read","tool_input":{"file_path":"%s"}}' "$1"; }
t "push origin main"                 deny  "$(b 'git push origin main')"
t "push HEAD:master"                 deny  "$(b 'git push -u origin HEAD:master')"
t "force push dev"                   deny  "$(b 'git push --force origin dev')"
t "push feat/x-main (allowed)"       allow "$(b 'git push -u origin feat/x-main')"
t "push larry/fix (allowed)"         allow "$(b 'git push -u origin larry/fix')"
t "gh pr merge"                      deny  "$(b 'gh pr merge 42 --squash')"
t "git merge main into feature"      allow "$(b 'git merge main')"
t "pnpm run db:push"                 deny  "$(b 'cd apps/dashboard && pnpm run db:push')"
t "npx drizzle-kit push"             deny  "$(b 'npx drizzle-kit push')"
t "prisma db push"                   deny  "$(b 'npx prisma db push')"
t "pnpm run db:migrate"              allow "$(b 'pnpm run db:migrate')"
t "rm -rf ~"                         deny  "$(b 'rm -rf ~')"
t "rm -rf /"                         deny  "$(b 'rm -rf /')"
t "rm -rf dist"                      allow "$(b 'rm -rf dist')"
t "cat .env"                         deny  "$(b 'cat .env')"
t "cat apps/becca/.env.local"        deny  "$(b 'cat apps/becca/.env.local')"
t "head -n 5 .env"                   deny  "$(b 'head -n 5 .env')"
t "tail .env | grep X"               deny  "$(b 'tail .env | grep X')"
t "cat .env.example"                 allow "$(b 'cat .env.example')"
t "heredoc mentioning .env"          allow "$(b 'cat > README.md <<EOF\ncopy .env into place\nEOF')"
t "cat notes | grep .env"            allow "$(b 'cat notes.md | grep .env')"
t "grep NEON .env"                   allow "$(b 'grep NEON .env')"
t "printf .env > .worktreeinclude"   allow "$(b 'printf .env > .worktreeinclude')"
t "Read .env"                        deny  "$(r '/x/.env')"
t "Read .env.local"                  deny  "$(r '/x/.env.local')"
t "Read .env.example"                allow "$(r '/x/.env.example')"
t "pnpm test"                        allow "$(b 'pnpm test')"

# 2b + 6. PR merge / create, built with jq so quotes and newlines are exact.
# U = repo with an unreviewed HEAD, V = repo whose HEAD has the review mark.
U="$(mktemp -d)"; V="$(mktemp -d)"; N="$(mktemp -d)"; trap 'rm -rf "$U" "$V" "$N"' EXIT
for r in "$U" "$V"; do git -C "$r" init -q && git -C "$r" -c user.email=t@t -c user.name=t commit -q --allow-empty -m one; done
(cd "$V" && bash "$(dirname "$G")/../skills/review-gate/scripts/mark-reviewed.sh" "test pass" >/dev/null)
c() { jq -nc --arg d "$1" --arg c "$2" '{tool_name:"Bash",cwd:$d,tool_input:{command:$c}}'; }
NL=$'\n'; P='gh pr'

t "merge: gh -R o/r pr merge"          deny  "$(c "$V" "gh -R o/r pr merge 1")"
t "merge: gh api PUT .../merge"        deny  "$(c "$V" "gh api -X PUT repos/o/r/pulls/1/merge")"
t "merge: graphql mergePullRequest"    deny  "$(c "$V" "gh api graphql -f query='mutation{mergePullRequest(input:{})}'")"

t "create: no review"                  deny  "$(c "$U" "$P create --fill")"
t "create: reviewed"                   allow "$(c "$V" "$P create --fill")"
t "create: view is fine"               allow "$(c "$U" "$P view")"
t "create: --help counts (strict)"     deny  "$(c "$U" "$P create --help")"
t "create: new commit after review"    deny  "$(cd "$V" && git -c user.email=t@t -c user.name=t commit -q --allow-empty -m two; c "$V" "$P create --fill")"
(cd "$V" && bash "$(dirname "$G")/../skills/review-gate/scripts/mark-reviewed.sh" "test pass" >/dev/null)
t "create: not a git repo (fail closed)" deny "$(c "$N" "gh -R o/r pr create --head feat")"

t "bypass: gh pr new"                  deny  "$(c "$U" "$P new --fill")"
t "bypass: gh -R o/r pr create"        deny  "$(c "$U" "gh -R o/r pr create --fill")"
t "bypass: GH_REPO=x gh pr create"     deny  "$(c "$U" "GH_REPO=o/r $P create --fill")"
t "bypass: env gh"                     deny  "$(c "$U" "env $P create --fill")"
t "bypass: command gh"                 deny  "$(c "$U" "command $P create")"
t "bypass: full path gh"               deny  "$(c "$U" "/opt/homebrew/bin/$P create")"
t "bypass: backslash gh"               deny  "$(c "$U" "\\$P create")"
t "bypass: { ...; }"                   deny  "$(c "$U" "{ $P create; }")"
t "bypass: xargs"                      deny  "$(c "$U" "echo x | xargs $P create")"
t "bypass: gh api POST pulls"          deny  "$(c "$U" "gh api repos/o/r/pulls -f head=b -f base=dev -f title=t")"
t "bypass: cd other repo (reviewed cwd)" deny "$(c "$V" "cd $U && $P create --fill")"
t "bypass: commit in same command"     deny  "$(c "$V" "git commit --allow-empty -m w && $P create --fill")"

t "bypass: graphql createPullRequest"  deny  "$(c "$U" "gh api graphql -f query='mutation { createPullRequest(input:{}) }'")"
t "bypass: multi-line gh api POST"     deny  "$(c "$U" "gh api repos/o/r/pulls \\${NL} -f title=t -f head=b")"
t "bypass: gh api -fhead= attached"    deny  "$(c "$U" "gh api repos/o/r/pulls -fhead=b -fbase=dev")"
t "bypass: g''h pr 'create'"           deny  "$(c "$U" "g''h pr 'create' --fill")"
t "bypass: --head other (reviewed)"    deny  "$(c "$V" "$P create --head other --fill")"
t "bypass: -R other (reviewed)"        deny  "$(c "$V" "gh -R o/other pr create --fill")"
t "bypass: git -c k=v commit && create" deny "$(c "$V" "git -c user.name=x commit -qm w && $P create --fill")"
t "bypass: npm version && create"      deny  "$(c "$V" "npm version patch && $P create --fill")"
t "merge: quoted \"gh\" pr merge"       deny  "$(c "$V" "\"gh\" pr merge 1")"
t "merge: gh pr \\newline merge"        deny  "$(c "$V" "$P \\${NL} merge 1")"
t "merge: enablePullRequestAutoMerge"  deny  "$(c "$V" "gh api graphql -f query='mutation{enablePullRequestAutoMerge(input:{})}'")"
t "mention counts (strict)"            deny  "$(c "$U" "git commit -m 'next: $P create'")"
t "other gh pr verbs (allowed)"        allow "$(c "$U" "gh pr view 3; gh pr list --search create; gh pr checks")"
t "create from file body (reviewed)"   allow "$(c "$V" "$P create --title 'Add login' --body-file .git/pr-body.md")"

# 1. pushes: the branch you are on, +refspec force, refs/heads/main
M="$(mktemp -d)"; F="$(mktemp -d)"; trap 'rm -rf "$U" "$V" "$N" "$M" "$F"' EXIT
git -C "$M" init -q -b main; git -C "$F" init -q -b main; git -C "$F" checkout -q -b feat
t "push HEAD:refs/heads/main"          deny  "$(c "$F" "git push origin HEAD:refs/heads/main")"
t "push +feat (force refspec)"         deny  "$(c "$F" "git push origin +feat")"
t "push -uf (force in short flags)"    deny  "$(c "$F" "git push -uf origin feat")"
t "bare push while on main"            deny  "$(c "$M" "git push")"
t "push -u origin HEAD while on main"  deny  "$(c "$M" "git push -u origin HEAD")"
t "bare push on a branch (allowed)"    allow "$(c "$F" "git push")"
t "push branch && rm -f (allowed)"     allow "$(c "$F" "git push -u origin feat && rm -f x.tmp")"
t "push tag on a branch (allowed)"     allow "$(c "$F" "git push origin v1.2.0")"
t "push: git -C path origin main"     deny  "$(c "$F" "git -C /x push origin main")"
t "push: git -c k=v push origin main"  deny  "$(c "$F" "git -c user.name=x push origin main")"
t "push: git -C . push --force"        deny  "$(c "$F" "git -C . push --force origin feat")"
t "push: quoted \"main\""              deny  "$(c "$F" "git push origin \"main\"")"
t "push: feat:\"main\""                deny  "$(c "$F" "git push origin feat:\"main\"")"
t "push: (git push origin main)"       deny  "$(c "$F" "(git push origin main)")"
t "push: split with backslash-newline" deny  "$(c "$F" "git push \\${NL}  origin main")"
t "push: --all / --mirror"             deny  "$(c "$F" "git push --all origin")"
t "push: --mirror is a force"          deny  "$(c "$F" "git push --mirror origin")"
t "push: \"+feat\" quoted force"       deny  "$(c "$F" "git push origin \"+feat\"")"
t "push on main: @"                    deny  "$(c "$M" "git push origin @")"
t "push on main: -o ci.skip origin"    deny  "$(c "$M" "git push -o ci.skip origin")"
t "push on main: via git -C path"      deny  "$(c "$F" "git -C $M push")"
t "push on main: cd && bare push"      deny  "$(c "$F" "cd $M && git push")"
t "push on main: --tags (allowed)"     allow "$(c "$M" "git push --tags")"
t "push on main: --delete old (allowed)" allow "$(c "$M" "git push origin --delete old-branch")"
t "push on main: --dry-run (allowed)"  allow "$(c "$M" "git push --dry-run")"
t "push: delete main"                  deny  "$(c "$F" "git push origin --delete main")"
t "merge: GH (case, macOS)"            deny  "$(c "$V" "GH pr merge 12")"
t "create: GH (case, macOS)"           deny  "$(c "$U" "GH pr create --fill")"
t "gh api GET pulls (allowed)"         allow "$(c "$U" "gh api -X GET repos/o/r/pulls -f state=closed")"
# round 4: lines, wrappers, redirects, switches, paths
W="$(mktemp -d)/My Repo"; mkdir -p "$W"; git -C "$W" init -q -b main
H2="$HOME/.harness-test-$$"; git init -q -b main "$H2"; trap 'rm -rf "$U" "$V" "$N" "$M" "$F" "$H2"' EXIT
t "push: line 3 of add/commit/push"    deny  "$(c "$F" "git add -A${NL}git commit -m x${NL}git push origin main")"
t "push: line 2 force"                 deny  "$(c "$F" "git status${NL}git push -f origin feat")"
t "push: timeout 60 git push"          deny  "$(c "$F" "timeout 60 git push origin main")"
t "push: env value with spaces"        deny  "$(c "$F" "GIT_SSH_COMMAND=\"ssh -o BatchMode=yes\" git push origin main")"
t "push: if/then"                      deny  "$(c "$F" "if true; then git push origin main; fi")"
t "push: for/do"                       deny  "$(c "$F" "for r in origin; do git push \$r main; done")"
t "push: { ...; }"                     deny  "$(c "$F" "{ git push origin main; }")"
t "push: ! git push"                   deny  "$(c "$F" "! git push --force origin feat")"
t "push: xargs git push"               deny  "$(c "$F" "echo | xargs git push origin main")"
t "push: main>/dev/null"               deny  "$(c "$F" "git push origin main>/dev/null")"
t "push on main: origin 2>&1 | tail"   deny  "$(c "$M" "git push origin 2>&1 | tail -5")"
t "push on main: -u origin >/dev/null" deny  "$(c "$M" "git push -u origin >/dev/null")"
t "push: checkout main && push"        deny  "$(c "$F" "git checkout main && git merge feat && git push")"
t "push: switch main && push HEAD"     deny  "$(c "$F" "git switch main && git push origin HEAD")"
t "push: -C ~/repo on main"            deny  "$(c "$F" "git -C ~/${H2#$HOME/} push")"
t "push: -C \$HOME/repo on main"        deny  "$(c "$F" "git -C \$HOME/${H2#$HOME/} push")"
t "push: -C path with a space"         deny  "$(c "$F" "git -C \"$W\" push origin main")"
t "push: -C missing path"              deny  "$(c "$F" "git -C /no/such/repo push")"
t "push: cd && relative -C"            deny  "$(c "$F" "cd /tmp && git -C sub push")"
t "push: HEAD:heads/main"              deny  "$(c "$F" "git push origin HEAD:heads/main")"
t "push: glob refspec"                 deny  "$(c "$F" "git push origin 'refs/heads/*:refs/heads/*'")"
t "push: matching ':'"                 deny  "$(c "$F" "git push origin :")"
t "push: -c push.default=matching"     deny  "$(c "$F" "git -c push.default=matching push")"
t "on main: HEAD:fix-oops (allowed)"   allow "$(c "$M" "git push origin HEAD:fix-oops")"
t "on main: HEAD:refs/heads/x (allowed)" allow "$(c "$M" "git push -u origin HEAD:refs/heads/fix-x")"
t "feat:Main (allowed, case)"          allow "$(c "$F" "git push origin feat:Main")"
t "feat: 2>&1 with branch (allowed)"   allow "$(c "$F" "git push -u origin feat 2>&1 | tail -3")"
t "feat: multi-line normal (allowed)"  allow "$(c "$F" "git add -A${NL}git commit -m wip${NL}git push -u origin feat")"
t "push -C feat repo from main (ok)"  allow "$(c "$M" "git -C $F push")"
t "commit msg says push main (allowed)" allow "$(c "$F" "git commit -m \"push to main later\"")"
t "git stash push (allowed)"           allow "$(c "$F" "git stash push -m x")"
echo; echo "passed=$PASS failed=$FAIL"
[ "$FAIL" = 0 ]
